package com.vanguard.engine;

import com.vanguard.domain.dto.MetaApiDtos.MetricObstacle;
import com.vanguard.domain.dto.MetaApiDtos.MetricWaypoint;
import com.vanguard.domain.dto.MetaApiDtos.Ros2ExportBundle;
import com.vanguard.domain.dto.MetaApiDtos.VerificationReport;
import org.springframework.stereotype.Service;

import java.util.List;
import java.util.Locale;

/**
 * Generates standard ROS 2 Humble / Jazzy Nav2 occupancy grid packages:
 *   1. map.pgm (ASCII P2 trinary occupancy grid:
 *        0   = OCCUPIED (corridor walls & detected obstacle footprints)
 *        205 = UNKNOWN  (monocular occlusion shadow behind obstacles where floor is unobserved)
 *        254 = FREE     (observed & clear floor)
 *      NOTE: Kinematic inflation is NOT encoded as 128 in trinary PGM; inflation belongs to
 *      nav2_costmap_2d::InflationLayer and is exported separately in nav2CostmapParamsYaml.)
 *   2. map.yaml (Nav2 map_server metadata)
 *   3. nav2CostmapParamsYaml (Nav2 InflationLayer parameters matching robot_radius & stopping envelope)
 *   4. nav2_verified_waypoints.json (geometry_msgs/msg/PoseStamped array + cryptographic verification_hash;
 *      if verificationReport is REJECTED/UNVERIFIED, poses array is empty to prevent unsafe execution).
 */
@Service
public class Ros2ExportService {

    public static final double DEFAULT_RESOLUTION_M_PER_CELL = 0.05;

    public Ros2ExportBundle generateRos2Bundle(
            double corridorWidthMeters,
            double corridorLengthMeters,
            List<MetricObstacle> obstacles,
            List<MetricWaypoint> verifiedWaypoints,
            VerificationReport verificationReport,
            double velocityMs,
            double frictionMu) {
        return generateRos2Bundle(corridorWidthMeters, corridorLengthMeters, obstacles,
                verifiedWaypoints, verificationReport, velocityMs, frictionMu,
                "KINEGUARD_SCENE", null);
    }

    public Ros2ExportBundle generateRos2Bundle(
            double corridorWidthMeters,
            double corridorLengthMeters,
            List<MetricObstacle> obstacles,
            List<MetricWaypoint> verifiedWaypoints,
            VerificationReport verificationReport,
            double velocityMs,
            double frictionMu,
            String sceneId,
            String scaleType) {
        return generateRos2Bundle(corridorWidthMeters, corridorLengthMeters, obstacles,
                verifiedWaypoints, verificationReport, velocityMs, frictionMu,
                sceneId, scaleType, null);
    }

    public Ros2ExportBundle generateRos2Bundle(
            double corridorWidthMeters,
            double corridorLengthMeters,
            List<MetricObstacle> obstacles,
            List<MetricWaypoint> verifiedWaypoints,
            VerificationReport verificationReport,
            double velocityMs,
            double frictionMu,
            String sceneId,
            String scaleType,
            String executionId) {

        // Grid must cover exactly the declared corridor: cells = round(meters / resolution).
        // Padding the grid (previous 40/60 minimums) made origin [0,0] describe a larger map.
        int widthCells = Math.max(1, (int) Math.round(corridorWidthMeters / DEFAULT_RESOLUTION_M_PER_CELL));
        int heightCells = Math.max(1, (int) Math.round(corridorLengthMeters / DEFAULT_RESOLUTION_M_PER_CELL));
        String resolvedScaleType = (scaleType != null && !scaleType.isBlank())
                ? scaleType.trim().toUpperCase(Locale.ROOT) : "UNKNOWN";
        String resolvedExecutionId = (executionId != null && !executionId.isBlank())
                ? executionId.trim() : "UNKNOWN_EXECUTION";

        boolean isApproved = verificationReport != null && verificationReport.isApproved();
        String status = isApproved
                ? "APPROVED"
                : (verificationReport != null && verificationReport.getVerificationStatus() != null
                        && !verificationReport.getVerificationStatus().isBlank()
                        ? verificationReport.getVerificationStatus()
                        : "REJECTED");
        boolean isUnverified = "UNVERIFIED".equalsIgnoreCase(status);
        String hash = (verificationReport != null && verificationReport.getVerificationHash() != null)
                ? verificationReport.getVerificationHash()
                : "sha256:unverified";

        StringBuilder pgm = new StringBuilder();
        pgm.append("P2\n");
        pgm.append("# Generated by KineGuard ROS2 Studio - Verifiable Physical AI Navigation Compiler\n");
        pgm.append("# Trinary Nav2 encoding: 0=OCCUPIED, 205=UNKNOWN (monocular occlusion), 254=FREE\n");
        pgm.append(String.format(Locale.US, "# Grid: %.2fm x %.2fm @ %.2fm/cell (%dx%d)\n",
                corridorWidthMeters, corridorLengthMeters, DEFAULT_RESOLUTION_M_PER_CELL, widthCells, heightCells));
        pgm.append(widthCells).append(" ").append(heightCells).append("\n255\n");

        for (int row = heightCells - 1; row >= 0; row--) {
            double yMeters = (row + 0.5) * DEFAULT_RESOLUTION_M_PER_CELL;
            for (int col = 0; col < widthCells; col++) {
                double xMeters = (col + 0.5) * DEFAULT_RESOLUTION_M_PER_CELL;
                int cellVal = isUnverified ? 205 : 254; // UNKNOWN (205) if perception is unverified, else FREE (254)

                // Corridor perimeter walls on all four sides
                if (col == 0 || col == widthCells - 1 || row == 0 || row == heightCells - 1) {
                    cellVal = 0; // OCCUPIED wall
                } else if (obstacles != null) {
                    for (MetricObstacle obs : obstacles) {
                        double dx = xMeters - obs.getCenterXMeters();
                        double dy = yMeters - obs.getCenterYMeters();
                        double dist = Math.hypot(dx, dy);
                        if (dist <= obs.getRadiusMeters()) {
                            cellVal = 0; // OCCUPIED obstacle footprint
                            break;
                        } else if (dy > 0.0
                                && dy <= obs.getRadiusMeters() * 2.2
                                && Math.abs(dx) <= obs.getRadiusMeters() * 0.95) {
                            // Monocular occlusion shadow behind the obstacle (unobserved floor from camera at y=0)
                            cellVal = Math.min(cellVal, 205); // UNKNOWN in Nav2 trinary mode
                        }
                    }
                }
                pgm.append(cellVal).append(col == widthCells - 1 ? "\n" : " ");
            }
        }

        double dStop = verificationReport != null ? verificationReport.getStoppingDistanceMeters() : 0.62;
        double dReq = verificationReport != null ? verificationReport.getRequiredClearanceMeters() : 1.09;
        double dLat = verificationReport != null ? verificationReport.getLateralClearanceRequiredMeters() : 0.47;

        String yaml = String.format(Locale.US,
                "image: map.pgm\n"
                        + "mode: trinary\n"
                        + "resolution: %.3f\n"
                        + "origin: [0.000, 0.000, 0.000]\n"
                        + "negate: 0\n"
                        + "occupied_thresh: 0.65\n"
                        + "free_thresh: 0.196\n"
                        + "# KineGuard Audit: execution=%s, status=%s, scale_type=%s, verification_hash=%s, d_stop=%.3fm (v=%.2fm/s, mu=%.2f)\n",
                DEFAULT_RESOLUTION_M_PER_CELL,
                resolvedExecutionId,
                status,
                resolvedScaleType,
                hash,
                dStop,
                velocityMs,
                frictionMu
        );

        String costmapParamsYaml = String.format(Locale.US,
                "local_costmap:\n"
                        + "  local_costmap:\n"
                        + "    ros__parameters:\n"
                        + "      robot_radius: %.3f\n"
                        + "      plugins: [\"voxel_layer\", \"inflation_layer\"]\n"
                        + "      inflation_layer:\n"
                        + "        plugin: \"nav2_costmap_2d::InflationLayer\"\n"
                        + "        cost_scaling_factor: 3.0\n"
                        + "        inflation_radius: %.3f\n",
                KinematicSafetyKernel.ROBOT_RADIUS_METERS,
                dReq
        );

        StringBuilder wpJson = new StringBuilder();
        wpJson.append("{\n");
        wpJson.append("  \"action\": \"nav2_msgs/action/FollowWaypoints\",\n");
        wpJson.append("  \"header\": {\n");
        wpJson.append("    \"frame_id\": \"map\",\n");
        wpJson.append("    \"compiler\": \"KineGuard ROS2 Studio v2.1\",\n");
        wpJson.append(String.format(Locale.US, "    \"verification_status\": \"%s\",\n", status));
        wpJson.append(String.format(Locale.US, "    \"execution_id\": \"%s\",\n", resolvedExecutionId));
        wpJson.append(String.format(Locale.US, "    \"scale_type\": \"%s\",\n", resolvedScaleType));
        wpJson.append(String.format(Locale.US, "    \"verification_hash\": \"%s\",\n", hash));
        wpJson.append(String.format(Locale.US, "    \"kinematic_approved\": %s,\n", isApproved));
        wpJson.append(String.format(Locale.US, "    \"min_clearance_meters\": %.3f,\n",
                verificationReport != null ? verificationReport.getMinClearanceMeters() : 0.0));
        wpJson.append(String.format(Locale.US, "    \"lateral_clearance_required_meters\": %.3f,\n", dLat));
        wpJson.append(String.format(Locale.US, "    \"longitudinal_clearance_required_meters\": %.3f,\n", dReq));
        wpJson.append(String.format(Locale.US, "    \"stopping_distance_meters\": %.3f\n", dStop));
        wpJson.append("  },\n");
        wpJson.append("  \"poses\": [\n");

        // Only emit executable PoseStamped waypoints if the trajectory was formally APPROVED by KinematicSafetyKernel
        if (isApproved && verifiedWaypoints != null) {
            for (int i = 0; i < verifiedWaypoints.size(); i++) {
                MetricWaypoint wp = verifiedWaypoints.get(i);
                double nextX = (i + 1 < verifiedWaypoints.size()) ? verifiedWaypoints.get(i + 1).getXMeters() : wp.getXMeters();
                double nextY = (i + 1 < verifiedWaypoints.size()) ? verifiedWaypoints.get(i + 1).getYMeters() : wp.getYMeters() + 1.0;
                double yaw = Math.atan2(nextY - wp.getYMeters(), nextX - wp.getXMeters());
                double qz = Math.sin(yaw * 0.5);
                double qw = Math.cos(yaw * 0.5);

                wpJson.append(String.format(Locale.US,
                        "    {\"header\": {\"frame_id\": \"map\"}, \"id\": \"%s\", \"pose\": {\"position\": {\"x\": %.3f, \"y\": %.3f, \"z\": 0.0}, \"orientation\": {\"x\": 0.0, \"y\": 0.0, \"z\": %.4f, \"w\": %.4f}}, \"target_speed_mps\": %.2f}%s\n",
                        wp.getId(), wp.getXMeters(), wp.getYMeters(), qz, qw, wp.getTargetSpeedMs(),
                        (i == verifiedWaypoints.size() - 1) ? "" : ","));
            }
        }
        wpJson.append("  ]\n}");

        return Ros2ExportBundle.builder()
                .sceneId(sceneId != null && !sceneId.isBlank() ? sceneId : "KINEGUARD_SCENE")
                .executionId(resolvedExecutionId)
                .verificationStatus(status)
                .verificationHash(hash)
                .scaleType(resolvedScaleType)
                .mapPgmAscii(pgm.toString())
                .mapYaml(yaml)
                .nav2CostmapParamsYaml(costmapParamsYaml)
                .nav2WaypointsJson(wpJson.toString())
                .gridWidthCells(widthCells)
                .gridHeightCells(heightCells)
                .resolutionMetersPerPixel(DEFAULT_RESOLUTION_M_PER_CELL)
                .build();
    }
}
